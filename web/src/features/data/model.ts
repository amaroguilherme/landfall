// ---- provenance kinds (ingest/common.py PROVENANCE_KINDS) -------------------------------------

export const PROVENANCE_ORDER: readonly SnapshotProvenance[] = ['measured', 'predicted', 'reference', 'simulated', 'derived']

export const PROVENANCE_LABEL: Record<SnapshotProvenance, string> = {
  measured: 'Measured',
  predicted: 'Predicted',
  reference: 'Reference',
  simulated: 'Simulated',
  derived: 'Derived',
}

/** One plain-language line per kind, shown on every card and as the badge tooltip. */
export const PROVENANCE_WHAT: Record<SnapshotProvenance, string> = {
  measured: 'Real measured data (instrument or laboratory), as published by the source.',
  predicted: 'Real predictions computed by the publisher (ephemeris or forecast), not observations.',
  reference: 'Published reference material (standard, scale, list or web page), as retrieved.',
  simulated: 'Generated by LANDFALL from a fixed seed. Not real crew data.',
  derived: 'Computed by LANDFALL from other snapshots in this build.',
}

export function isProvenance(p: string): p is SnapshotProvenance {
  return (PROVENANCE_ORDER as readonly string[]).includes(p)
}

export function isSimulated(e: Pick<ManifestEntry, 'id' | 'provenance'>): boolean {
  return e.provenance === 'simulated' || e.id.startsWith('sim_')
}

// ---- publishers ---------------------------------------------------------------------------------

/** Short agency tag for a publisher string; null when it is none of the known agencies. */
export function agencyOf(publisher: string): 'NASA' | 'NOAA' | 'CSA' | 'LANDFALL' | null {
  if (/^NASA\b/.test(publisher)) return 'NASA'
  if (/^NOAA\b/.test(publisher)) return 'NOAA'
  if (/^Canadian Space Agency\b/.test(publisher)) return 'CSA'
  if (/^LANDFALL\b/.test(publisher)) return 'LANDFALL'
  return null
}

const AGENCY_RANK: Record<string, number> = { NASA: 0, NOAA: 1, CSA: 2, other: 3, LANDFALL: 4 }

export interface PublisherGroup {
  publisher: string
  /** DOM id of the group section (also the ?group= deep-link value). */
  slug: string
  entries: ManifestEntry[]
}

function slugify(s: string): string {
  return s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 48)
}

const byId = (a: ManifestEntry, b: ManifestEntry) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0)

/** Groups by the exact publisher string: NASA first, then NOAA, CSA, others, LANDFALL last. */
export function groupByPublisher(entries: readonly ManifestEntry[]): PublisherGroup[] {
  const map = new Map<string, ManifestEntry[]>()
  for (const e of entries) {
    const k = e.publisher?.trim() || 'Publisher not stated'
    const list = map.get(k)
    if (list) list.push(e)
    else map.set(k, [e])
  }
  const rank = (p: string) => AGENCY_RANK[agencyOf(p) ?? 'other']
  const groups = [...map].map(([publisher, list]) => ({ publisher, slug: '', entries: [...list].sort(byId) }))
  groups.sort((a, b) => rank(a.publisher) - rank(b.publisher) || a.publisher.localeCompare(b.publisher, 'en'))
  const used = new Set<string>()
  for (const g of groups) {
    let slug = `pub-${slugify(g.publisher) || 'unknown'}`
    for (let i = 2; used.has(slug); i++) slug = `pub-${slugify(g.publisher)}-${i}`
    used.add(slug)
    g.slug = slug
  }
  return groups
}

// ---- page totals --------------------------------------------------------------------------------

export interface Stats {
  count: number
  bytes: number
  byProvenance: Record<SnapshotProvenance, ManifestEntry[]>
  /** Past stale_after (or past the end of a prediction window), judged on the wall clock. */
  stale: ManifestEntry[]
  firstRetrieved: string | null
  lastRetrieved: string | null
  /** Agencies behind the non-simulated snapshots, in display order. */
  realAgencies: string[]
}

export function computeStats(entries: readonly ManifestEntry[], now: Date = new Date()): Stats {
  const byProvenance = Object.fromEntries(PROVENANCE_ORDER.map((p) => [p, [] as ManifestEntry[]])) as Record<
    SnapshotProvenance,
    ManifestEntry[]
  >
  let bytes = 0
  let first: string | null = null
  let last: string | null = null
  const stale: ManifestEntry[] = []
  const agencies = new Set<string>()
  for (const e of entries) {
    bytes += Number.isFinite(e.bytes) ? e.bytes : 0
    if (isProvenance(e.provenance)) byProvenance[e.provenance].push(e)
    const t = Date.parse(e.retrieved_at)
    if (Number.isFinite(t)) {
      if (first === null || t < Date.parse(first)) first = e.retrieved_at
      if (last === null || t > Date.parse(last)) last = e.retrieved_at
    }
    if (freshnessOf(e, 'ready', now).state === 'stale') stale.push(e)
    if (!isSimulated(e)) agencies.add(agencyOf(e.publisher) ?? e.publisher)
  }
  const realAgencies = [...agencies].sort((a, b) => (AGENCY_RANK[a] ?? 3) - (AGENCY_RANK[b] ?? 3) || a.localeCompare(b, 'en'))
  return { count: entries.length, bytes, byProvenance, stale: stale.sort(byId), firstRetrieved: first, lastRetrieved: last, realAgencies }
}

/** "A", "A and B", "A, B and C". */
export function joinAnd(items: readonly string[]): string {
  if (items.length <= 1) return items.join('')
  return `${items.slice(0, -1).join(', ')} and ${items[items.length - 1]}`
}

