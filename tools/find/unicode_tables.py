"""Write web/src/features/find/unicode.ts: the character classes of Hugging Face tokenizers 0.23.3's BertNormalizer
and BertPreTokenizer, read off the tokenizer itself one code point at a time.

The Rust tokenizer classifies characters with its own Unicode tables (the unicode_categories crate, older than the
browser's), so the TypeScript port does not use the browser's \\p{...} classes for them. For every code point this
script asks the real tokenizer:

    removed     dropped by clean_text (NUL, U+FFFD, and its control, format, private-use and surrogate classes)
    whitespace  turned into a space by clean_text; split whitespace: what the pre-tokenizer splits on
    punctuation split into its own token by the pre-tokenizer
    nonspacing  dropped by strip_accents after NFD (a code point that NFD leaves alone and strip_accents drops)

It also prints the SHA-256 of one line per code point, "<hex>\\t<normalised>\\t<class>\\n", which the test
recomputes with the TypeScript port (fixtures/codepoints.json).

    uv run --isolated --no-project --with tokenizers==0.23.3 python -I tools/find/unicode_tables.py \\
      /tmp/lf-models/potion8m/tokenizer.json web/src/features/find
"""

from __future__ import annotations

import hashlib
import json
import sys
import unicodedata
from pathlib import Path

TOKENIZER_SHA = "e67e803f624fb4d67dea1c730d06e1067e1b14d830e2c2202569e3ef0f70bb50"
# Code points with a canonical decomposition in Unicode 13 to 17 (Dives Akuru, Todhri, Tulu-Tigalari, Gurung Khema,
# Kirat Rai) that the tokenizer's older NFD tables leave whole. Found by comparing every code point with the port
# under Node 25 (ICU 78.2, Unicode 17); the code-point test re-checks the list.
NO_NFD = [0x105C9, 0x105E4, 0x11383, 0x11385, 0x1138E, 0x11391, 0x113C5, 0x113C7, 0x113C8, 0x11938,
          *range(0x16121, 0x16129), 0x16D68, 0x16D69, 0x16D6A]


def ranges(cps: list[int]) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    for cp in cps:
        if out and cp == out[-1][1] + 1:
            out[-1] = (out[-1][0], cp)
        else:
            out.append((cp, cp))
    return out


def encode(rs: list[tuple[int, int]]) -> str:
    """Ranges as 'start-end' or 'start' in base 36, comma-separated: compact and readable."""

    def b36(n: int) -> str:
        digits = "0123456789abcdefghijklmnopqrstuvwxyz"
        s = ""
        while True:
            n, r = divmod(n, 36)
            s = digits[r] + s
            if n == 0:
                return s

    return ",".join(b36(a) if a == b else f"{b36(a)}-{b36(b)}" for a, b in rs)


def main(argv: list[str]) -> int:
    tok_path, out_dir = Path(argv[1]), Path(argv[2])
    if hashlib.sha256(tok_path.read_bytes()).hexdigest() != TOKENIZER_SHA:
        raise SystemExit("tokenizer.json does not match the pinned revision")
    from tokenizers import Tokenizer
    from tokenizers.normalizers import BertNormalizer

    tok = Tokenizer.from_file(str(tok_path))
    full = tok.normalizer
    pre = tok.pre_tokenizer
    clean = BertNormalizer(clean_text=True, handle_chinese_chars=False, strip_accents=False, lowercase=False)
    strip = BertNormalizer(clean_text=False, handle_chinese_chars=False, strip_accents=True, lowercase=False)

    removed: list[int] = []
    whitespace: list[int] = []
    split: list[int] = []
    punct: list[int] = []
    nonspacing: list[int] = []
    h = hashlib.sha256()
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        c = chr(cp)
        cl = clean.normalize_str(c)
        if cl == "":
            removed.append(cp)
        elif cl == " " and c != " ":
            whitespace.append(cp)
        elif c == " ":
            whitespace.append(cp)
        # strip_accents alone: a code point NFD leaves as itself that is dropped is non-spacing for the port.
        if unicodedata.normalize("NFD", c) == c and strip.normalize_str(c) == "":
            nonspacing.append(cp)
        if cp in NO_NFD and strip.normalize_str(c) != c:
            raise SystemExit(f"U+{cp:04X} is decomposed by the tokenizer after all")
        pieces = [p for p, _ in pre.pre_tokenize_str("a" + c + "b")]
        cls = "w" if pieces == ["a", "b"] else "p" if pieces == ["a", c, "b"] else "o"
        if cls == "p":
            punct.append(cp)
        elif cls == "w":
            split.append(cp)
        h.update(f"{cp:x}\t{full.normalize_str(c)}\t{cls}\n".encode("utf-8", "surrogatepass"))

    tables = {
        "REMOVED": ranges(removed),
        "WHITESPACE": ranges(whitespace),
        "SPLIT_WHITESPACE": ranges(split),
        "PUNCTUATION": ranges(punct),
        "NONSPACING": ranges(nonspacing),
        "NO_NFD": ranges(sorted(NO_NFD)),
    }
    lines = [
        "// GENERATED by tools/find/unicode_tables.py from Hugging Face tokenizers 0.23.3 (potion-base-8M's tokenizer.json,",
        "// SHA-256 e67e803f...). Do not edit: rerun the script. Each table lists code-point ranges in base 36,",
        "// \"start-end\" or \"start\", read off the Rust tokenizer one code point at a time, so the port classifies",
        "// characters as it does, not as the browser's newer Unicode tables would.",
        "",
    ]
    doc = {
        "REMOVED": "Dropped by BertNormalizer clean_text: NUL, U+FFFD and the tokenizer's control/format/private-use classes.",
        "WHITESPACE": "Turned into a space by clean_text.",
        "SPLIT_WHITESPACE": "Split on, and removed, by BertPreTokenizer (Rust char::is_whitespace).",
        "PUNCTUATION": "Split into its own token by BertPreTokenizer (ASCII punctuation and the tokenizer's Unicode P* classes).",
        "NONSPACING": "Dropped by strip_accents after NFD (the tokenizer's Mn class).",
        "NO_NFD": "Left whole by the tokenizer's NFD although Unicode 13-17 decomposes them.",
    }
    for name, rs in tables.items():
        lines.append(f"/** {doc[name]} {len(rs)} ranges. */")
        lines.append(f"export const {name} = '{encode(rs)}'")
        lines.append("")
    (out_dir / "unicode.ts").write_text("\n".join(lines), encoding="utf-8")
    fixture = {
        "about": "SHA-256 of one line per code point (U+0000..U+10FFFF without surrogates): '<hex>\\t<BertNormalizer output>\\t<w|p|o>\\n', "
        "where the class is the BertPreTokenizer's on 'a' + c + 'b' (w: whitespace, p: punctuation, o: other). From Hugging Face tokenizers 0.23.3.",
        "tokenizer_sha256": TOKENIZER_SHA,
        "code_points": 0x110000 - 0x800,
        "sha256": h.hexdigest(),
        "sizes": {k: len(v) for k, v in tables.items()},
    }
    (out_dir / "fixtures" / "codepoints.json").write_text(json.dumps(fixture, indent=1) + "\n", encoding="utf-8")
    print(json.dumps(fixture, indent=1))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
