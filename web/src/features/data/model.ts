/** Same page? (scheme, host case and a trailing slash are ignored). */
export function sameUrl(a: string | null | undefined, b: string | null | undefined): boolean {
  const norm = (u: string) => u.trim().replace(/^https?:\/\//i, '').replace(/\/+$/, '').replace(/^[^/]+/, (h) => h.toLowerCase())
  return !!a && !!b && norm(a) === norm(b)
}

// ---- access URLs ------------------------------------------------------------------------------

export type AccessUrl =
  | { kind: 'external'; href: string }
  | { kind: 'snapshot'; id: string; text: string }
  | { kind: 'other'; text: string }

/** sim_crew lists the frozen files it replays as repo paths ("web/public/data/<id>.json"). */
export function classifyAccessUrl(u: string): AccessUrl {
  if (/^https?:\/\//i.test(u)) return { kind: 'external', href: u }
  const m = /(?:^|\/)data\/([a-z0-9_]+)\.json$/.exec(u)
  if (m) return { kind: 'snapshot', id: m[1], text: u }
  return { kind: 'other', text: u }
}

// ---- durations and dates ----------------------------------------------------------------------

export type DurationUnit = 'd' | 'h' | 'min' | 's'

/** Exact, unrounded parts: 3600 -> [1 h], 82800 -> [23 h], 90 -> [1 min, 30 s]. */
export function durationParts(seconds: number): { value: number; unit: DurationUnit }[] {
  let s = Math.max(0, Math.round(seconds))
  const out: { value: number; unit: DurationUnit }[] = []
  const take = (size: number, unit: DurationUnit) => {
    const n = Math.floor(s / size)
    s -= n * size
    if (n) out.push({ value: n, unit })
  }
  take(86_400, 'd')
  take(3600, 'h')
  take(60, 'min')
  if (s || out.length === 0) out.push({ value: s, unit: 's' })
  return out
}

